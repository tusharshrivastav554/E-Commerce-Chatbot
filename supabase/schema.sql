-- Supabase schema for the e-commerce product-review RAG application.
-- Run this script in the Supabase SQL Editor before running:
--     python -m ecommbot.ingest

create extension if not exists vector
with schema extensions;

create table if not exists public.chatbotecomm (
    id bigint generated by default as identity primary key,
    content text not null,
    metadata jsonb not null default '{}'::jsonb,
    embedding extensions.vector(768) not null
);

create or replace function public.match_documents(
    query_embedding extensions.vector(768)
)
returns table (
    id bigint,
    content text,
    metadata jsonb,
    similarity double precision
)
stable
as $$
    select
        d.id,
        d.content,
        d.metadata,
        1 - (d.embedding <=> query_embedding) as similarity
    from public.chatbotecomm as d
    order by d.embedding <=> query_embedding;
$$
language sql;

create index if not exists chatbotecomm_embedding_idx
on public.chatbotecomm
using hnsw (embedding vector_cosine_ops);

